# icon/mon_7.bin (colour 48x30) and mon_8.bin (mono 48x30) -> app/icon.inc
# (the bitmap part of the moniker: after type, size, GR opcode and length)
import os
HERE = os.path.dirname(os.path.abspath(__file__))
def emit(name, path):
    b = open(path, 'rb').read()[8:-1]
    out = ['%s:' % name]
    for i in range(0, len(b), 16):
        out.append(' db ' + ','.join('0x%02x' % c for c in b[i:i+16]))
    return out
lines = ['; generated by tools/gen_icon_inc.py - do not edit']
lines += emit('icon_bmp', os.path.join(HERE, '..', 'icon', 'mon_7.bin'))
lines += emit('icon_mono', os.path.join(HERE, '..', 'icon', 'mon_8.bin'))
open(os.path.join(HERE, '..', 'app', 'icon.inc'), 'w').write('\n'.join(lines) + '\n')
