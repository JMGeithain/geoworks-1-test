# texts_de.txt (UTF-8) -> app/texts.inc (GEOS character set = Mac Roman)
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
FALLBACK = {'×': 'x', '↑': 'auf', '↓': 'ab', '−': '-', '→': '->'}
def enc(t):
    for k, v in FALLBACK.items():
        t = t.replace(k, v)
    return t.encode('mac_roman')
def db(b):
    out, lit = [], b''
    for c in b:
        if 32 <= c < 127 and c != 39:
            lit += bytes([c])
        else:
            if lit: out.append("'%s'" % lit.decode()); lit = b''
            out.append('0x%02x' % c)
    if lit: out.append("'%s'" % lit.decode())
    return ','.join(out) if out else ''
lines = open(os.path.join(HERE, 'texts_de.txt'), encoding='utf-8').read().splitlines()
res = ['; generated by tools/gen_texts.py from tools/texts_de.txt - do not edit', '']
mode = None
for ln in lines:
    if not ln.strip() or ln.startswith('#'):
        if mode and mode != 'str' and not ln.strip() and False: pass
        continue
    m = re.match(r'\[(\w+)(?:\s+(\w+))?\]', ln)
    if m:
        if mode and mode != 'str': res.append(' db 0xff')
        mode = m.group(1)
        if mode == 'lines': res.append('%s:' % m.group(2))
        continue
    if mode == 'str':
        k, v = ln.split('=', 1)
        d = db(enc(v.strip()))
        res.append('%s: db %s0' % (k.strip(), d + ',' if d else ''))
    else:
        t, _, text = ln.partition(' ')
        d = db(enc(text))
        res.append(' db %s,%s0' % (t, d + ',' if d else ''))
if mode and mode != 'str': res.append(' db 0xff')
open(os.path.join(HERE, '..', 'app', 'texts.inc'), 'w').write('\n'.join(res) + '\n')
print(len(res), 'lines')
